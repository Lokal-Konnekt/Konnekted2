"""Generates Lokal's accent launcher icons from the desktop logo.

Desktop paints the theme accent through a mask cut to the logo's sticker
(public/lokal-icon-sticker.png). Bake the sticker color into each adaptive
foreground: bitmap tint inside a layer-list is not reliable on all launchers.

Run from the repo root after the logo changes:
  python3 tool/gen_lokal_launcher_icons.py
"""

from pathlib import Path

from PIL import Image

LOGO = Path('assets/branding/lokal_icon.png')
STICKER = Path('assets/branding/lokal_icon_sticker.png')
RES = Path('android/app/src/main/res')

# Must match LokalAccent.presets in lib/core/theme/lokal_tokens.dart.
ACCENTS = {
    'lime': '#C8FF57',
    'purple': '#7C6AFF',
    'pink': '#FF57C8',
    'orange': '#FF9F43',
    'blue': '#57B8FF',
    'red': '#FF5757',
    'teal': '#57FFD4',
    'white': '#FFFFFF',
    'yellow': '#FFEC57',
    'cyan': '#57FFEC',
    'magenta': '#FF57EC',
    'gray': '#888888',
    'chartreuse': '#E8FF57',
    'midnight': '#58A6FF',
    'rosegold': '#FFB7C5',
    'neon': '#FF00FF',
}
DEFAULT = 'lime'
BACKGROUND = '#0A0A0A'  # desktop Dark theme bg

DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}

# The logo fills 62 % of the 108 dp canvas: big enough to read on a home
# screen, at the cost of the case's corners on circular masks.
SCALE = .62


def place(image: Image.Image, px: int) -> Image.Image:
    canvas = Image.new('RGBA', (px, px), (0, 0, 0, 0))
    side = round(px * SCALE)
    scaled = image.resize((side, side), Image.LANCZOS)
    offset = (px - side) // 2
    canvas.alpha_composite(scaled, (offset, offset))
    return canvas


def main() -> None:
    logo = Image.open(LOGO).convert('RGBA')
    sticker = Image.open(STICKER).convert('RGBA')
    for name, factor in DENSITIES.items():
        px = round(108 * factor)
        folder = RES / f'drawable-{name}'
        folder.mkdir(parents=True, exist_ok=True)
        base = place(logo, px)
        for obsolete in ('base', 'sticker'):
            (folder / f'ic_lokal_fg_{obsolete}.png').unlink(missing_ok=True)
        for accent, color in ACCENTS.items():
            tinted = Image.new('RGBA', logo.size, color)
            tinted.putalpha(sticker.getchannel('A'))
            foreground = logo.copy()
            foreground.alpha_composite(tinted)
            place(foreground, px).save(
                folder / f'ic_lokal_fg_{accent}.png', optimize=True,
            )
        mono = Image.new('RGBA', (px, px), (255, 255, 255, 0))
        mono.putalpha(base.getchannel('A'))
        mono.save(folder / 'ic_lokal_fg_mono.png', optimize=True)

        # Legacy square icon, for launchers that ignore adaptive icons.
        legacy_px = round(48 * factor)
        legacy = Image.new('RGBA', (legacy_px, legacy_px), BACKGROUND)
        tinted = Image.new('RGBA', logo.size, ACCENTS[DEFAULT])
        tinted.putalpha(sticker.getchannel('A'))
        full = logo.copy()
        full.alpha_composite(tinted)
        side = round(legacy_px * .82)
        legacy.alpha_composite(
            full.resize((side, side), Image.LANCZOS),
            ((legacy_px - side) // 2, (legacy_px - side) // 2),
        )
        legacy.save(RES / f'mipmap-{name}' / 'launcher_icon.png', optimize=True)

    drawable = RES / 'drawable'
    anydpi = RES / 'mipmap-anydpi-v26'
    for accent, color in ACCENTS.items():
        (drawable / f'ic_lokal_fg_{accent}.xml').unlink(missing_ok=True)
        icon = (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by tool/gen_lokal_launcher_icons.py -->\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@color/lokal_icon_background" />\n'
            f'    <foreground android:drawable="@drawable/ic_lokal_fg_{accent}" />\n'
            '    <monochrome android:drawable="@drawable/ic_lokal_fg_mono" />\n'
            '</adaptive-icon>\n'
        )
        (anydpi / f'ic_lokal_{accent}.xml').write_text(icon)
        if accent == DEFAULT:
            (anydpi / 'launcher_icon.xml').write_text(icon)


if __name__ == '__main__':
    main()
